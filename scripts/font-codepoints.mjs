// Regenerates scripts/font-codepoints.txt: the code points the self-hosted font subsets must cover.
// Run after `npm run build` (it reads dist/index.html): node scripts/font-codepoints.mjs
// Then rebuild the fonts: python -I scripts/subset-fonts.py  (see that file).
//
// The list errs on the side of inclusion. It is the union of
//   1. a fixed base: Basic Latin, Latin-1 Supplement, General Punctuation, and everything in fontsource's
//      "latin" subset (so ordinary edits to the text never need a font rebuild);
//   2. every character in the pre-rendered page dist/index.html (scripts and styles removed, entities decoded;
//      attribute values such as title/aria-label are kept);
//   3. every character in the manuscript already-past-us.md and in src/**/*.{js,jsx,json,css}
//      (chart labels, data labels, CSS content strings).
// Control characters are dropped. Code points a font does not have are simply absent from its subset;
// scripts/subset-fonts.py reports them.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outFile = join(root, 'scripts', 'font-codepoints.txt')

// fontsource "latin" unicode-range plus Basic Latin / Latin-1 / General Punctuation.
const BASE_RANGES = [
  [0x20, 0x7e], [0xa0, 0xff], [0x2000, 0x206f],
  [0x131, 0x131], [0x152, 0x153], [0x2bb, 0x2bc], [0x2c6, 0x2c6], [0x2da, 0x2da], [0x2dc, 0x2dc],
  [0x304, 0x304], [0x308, 0x308], [0x329, 0x329], [0x20ac, 0x20ac], [0x2122, 0x2122],
  [0x2191, 0x2191], [0x2193, 0x2193], [0x2212, 0x2212], [0x2215, 0x2215], [0xfeff, 0xfeff], [0xfffd, 0xfffd],
]

const cps = new Map() // code point -> source label
const add = (cp, src) => {
  if (cp < 0x20 || (cp >= 0x7f && cp < 0xa0)) return // controls
  if (cp >= 0xd800 && cp <= 0xdfff) return
  if (!cps.has(cp)) cps.set(cp, src)
}
for (const [a, b] of BASE_RANGES) for (let cp = a; cp <= b; cp++) add(cp, 'base')
const addText = (text, src) => { for (const ch of text) add(ch.codePointAt(0), src) }

const NAMED = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ' }
const decode = (s) => s
  .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
  .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(parseInt(d, 10)))
  .replace(/&([a-z]+);/gi, (m, n) => NAMED[n.toLowerCase()] ?? m)

const html = join(root, 'dist', 'index.html')
if (!existsSync(html)) {
  console.error('dist/index.html not found: run npm run build first')
  process.exit(1)
}
const page = readFileSync(html, 'utf8')
  .replace(/<script\b[\s\S]*?<\/script>/gi, ' ')
  .replace(/<style\b[\s\S]*?<\/style>/gi, ' ')
  .replace(/<!--[\s\S]*?-->/g, ' ')
addText(decode(page), 'dist/index.html')
addText(readFileSync(join(root, 'already-past-us.md'), 'utf8'), 'already-past-us.md')

const walk = (dir) => readdirSync(dir).flatMap((f) => {
  const p = join(dir, f)
  return statSync(p).isDirectory() ? walk(p) : [p]
})
for (const p of walk(join(root, 'src'))) {
  if (/\.(jsx?|json|css)$/.test(p)) addText(readFileSync(p, 'utf8'), 'src/' + p.slice(join(root, 'src').length + 1).replace(/\\/g, '/'))
}

const hex = (cp) => 'U+' + cp.toString(16).toUpperCase().padStart(4, '0')
const sorted = [...cps.keys()].sort((a, b) => a - b)
const lines = [
  '# Code points the self-hosted font subsets cover. Generated by scripts/font-codepoints.mjs; do not edit by hand.',
  '# One per line: code point, character, first source it was found in ("base" = fixed base set).',
  ...sorted.map((cp) => `${hex(cp)}\t${cp === 0x20 ? 'space' : cp >= 0x2000 && cp <= 0x200f ? '(space/format)' : String.fromCodePoint(cp)}\t${cps.get(cp)}`),
]
writeFileSync(outFile, lines.join('\n') + '\n')
const extra = sorted.filter((cp) => cps.get(cp) !== 'base')
console.log(`font-codepoints.txt: ${sorted.length} code points (${extra.length} beyond the base set: ${extra.map(hex).join(' ')})`)
